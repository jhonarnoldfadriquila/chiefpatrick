-- Chef Patrick's Kitchen — PostgreSQL schema (Supabase or any PostgreSQL 13+).
-- Run through `npm run db:setup` (scripts/db-setup.mjs), or paste into the Supabase SQL editor
-- followed by database/seed.sql. Safe to re-run (CREATE TABLE IF NOT EXISTS).
--
-- Yes/no flags are SMALLINT 0/1. Row Level Security is switched on for every table with no
-- policies, so Supabase's public REST API (anon / authenticated keys) can't read or write them;
-- the app connects with the database password, which bypasses RLS.

-- ---------- staff accounts and sessions ----------

CREATE TABLE IF NOT EXISTS users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL,
  email         VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,             -- bcrypt
  role          VARCHAR(10) NOT NULL DEFAULT 'staff' CHECK (role IN ('admin','staff')),
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash  CHAR(64) PRIMARY KEY,                -- sha256 of the cookie token; the token itself is never stored
  user_id     INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  TIMESTAMPTZ NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions (expires_at);

-- ---------- menu ----------

CREATE TABLE IF NOT EXISTS menu_categories (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       VARCHAR(80) NOT NULL UNIQUE,
  name       VARCHAR(80) NOT NULL,
  position   INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS menu_items (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  INT NOT NULL REFERENCES menu_categories(id) ON DELETE CASCADE,
  name         VARCHAR(160) NOT NULL,
  note         VARCHAR(40) NULL,                   -- e.g. "+₱25"
  price        NUMERIC(10,2) NULL,                 -- internal; the public menu shows no prices
  image        VARCHAR(255) NULL,
  sold         INT NOT NULL DEFAULT 0 CHECK (sold >= 0), -- staff-maintained count for "Popular menu items"
  is_available SMALLINT NOT NULL DEFAULT 1,
  is_demo      SMALLINT NOT NULL DEFAULT 0,
  position     INT NOT NULL DEFAULT 0,
  created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_items_category ON menu_items (category_id, position);

-- ---------- catering packages ----------

CREATE TABLE IF NOT EXISTS packages (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(60) NOT NULL,
  tier        VARCHAR(20) NOT NULL DEFAULT 'gold',
  guests      INT NOT NULL CHECK (guests >= 0),
  price       NUMERIC(10,2) NOT NULL,
  for_who     VARCHAR(300) NOT NULL DEFAULT '',
  inclusions  JSONB NOT NULL,
  sample_menu JSONB NOT NULL,
  popular     SMALLINT NOT NULL DEFAULT 0,
  position    INT NOT NULL DEFAULT 0,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- bookings ----------

CREATE TABLE IF NOT EXISTS reservations (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  email       VARCHAR(190) NOT NULL,
  phone       VARCHAR(40) NOT NULL,
  event_date  DATE NOT NULL,
  event_time  CHAR(5) NOT NULL,                    -- HH:mm
  guests      INT NOT NULL CHECK (guests >= 0),
  event_type  VARCHAR(30) NOT NULL,
  message     TEXT NULL,
  status      VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','completed','cancelled')),
  notes       TEXT NULL,
  is_demo     SMALLINT NOT NULL DEFAULT 0,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_res_status ON reservations (status, created_at);
CREATE INDEX IF NOT EXISTS idx_res_date ON reservations (event_date);

CREATE TABLE IF NOT EXISTS events (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           VARCHAR(120) NOT NULL,
  event_type     VARCHAR(30) NOT NULL,
  event_date     DATE NOT NULL,
  event_time     CHAR(5) NULL,
  location       VARCHAR(160) NOT NULL DEFAULT '',
  guests         INT NOT NULL DEFAULT 0 CHECK (guests >= 0),
  amount         NUMERIC(12,2) NOT NULL DEFAULT 0,  -- contract value; feeds the revenue report
  status         VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','completed','cancelled')),
  notes          TEXT NULL,
  reservation_id INT NULL REFERENCES reservations(id) ON DELETE SET NULL,
  is_demo        SMALLINT NOT NULL DEFAULT 0,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_events_date ON events (event_date);

CREATE TABLE IF NOT EXISTS inquiries (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  email       VARCHAR(190) NOT NULL,
  phone       VARCHAR(40) NULL,
  subject     VARCHAR(120) NOT NULL,
  message     TEXT NOT NULL,
  status      VARCHAR(12) NOT NULL DEFAULT 'new' CHECK (status IN ('new','in_progress','resolved')),
  admin_note  TEXT NULL,
  is_demo     SMALLINT NOT NULL DEFAULT 0,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_inq_status ON inquiries (status, created_at);

-- ---------- website content ----------

CREATE TABLE IF NOT EXISTS gallery (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  src        VARCHAR(255) NOT NULL,
  width      INT NOT NULL,
  height     INT NOT NULL,
  alt        VARCHAR(200) NOT NULL,
  caption    VARCHAR(80) NULL,
  position   INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS venue_areas (
  id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     VARCHAR(100) NOT NULL,
  position INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS venues (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_id     INT NULL REFERENCES venue_areas(id) ON DELETE CASCADE, -- NULL = one of CPK's own halls
  name        VARCHAR(120) NOT NULL,
  address     VARCHAR(200) NULL,
  min_guests  INT NOT NULL DEFAULT 0,
  max_guests  INT NOT NULL,
  position    INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS testimonials (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote      VARCHAR(400) NOT NULL,
  author     VARCHAR(80) NOT NULL,
  event      VARCHAR(80) NOT NULL DEFAULT '',
  published  SMALLINT NOT NULL DEFAULT 1,
  is_sample  SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Restaurant info, contact, social links, SEO, appearance, kiddie menu: one JSON value per key.
CREATE TABLE IF NOT EXISTS settings (
  key        VARCHAR(40) PRIMARY KEY,
  value      JSONB NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

